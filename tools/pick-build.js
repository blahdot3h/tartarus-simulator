#!/usr/bin/env node
/* Tartarus Simulator: makes js/pick-data.js, what the screenshot reader
 * knows of instruments from labeled screenshots of the live game, beyond
 * js/scan-data.js:
 *   - picks: the instrument pick ("Select a Torture Instrument", at the
 *     start of a run): each card's art, by simulator id, left to right;
 *   - panels: board screenshots, with the instruments on the panel left of
 *     the board, left to right, so look-alike icons (the Barbed Collar and
 *     the Barbed Whip) are told apart by their own icons.
 *
 *   { "picks": { "pick-a.png": ["cage", "axe", "pestle"] },
 *     "panels": { "panel-a.png": ["collar", "keys"] } }   (tools/pick-truth.json)
 *
 *   node tools/pick-build.js [--dir trainingdata/picks]
 *
 * The screenshots aren't in the repo (see .gitignore). */
'use strict';

const fs = require('fs');
const path = require('path');
const P = require('./png.js');
const S = require('../js/scan.js');
const T = require('../js/engine.js');
const REF = require('../js/scan-data.js');
const TRUTH = require('./pick-truth.json');

const ROOT = path.join(__dirname, '..');
const argDir = process.argv.indexOf('--dir');
const DIR = path.resolve(ROOT, argDir > 0 ? process.argv[argDir + 1] : 'trainingdata/picks');

const round = (x, d) => Math.round(x * 10 ** d) / 10 ** d;
const pack = (f) => ({ grid: f.grid.map((x) => round(x, 1)), hist: f.hist.map((x) => round(x, 3)) });
// The reader's own id for each simulator instrument.
const readerId = {};
for (const [id, v] of Object.entries(REF.toolNames)) if (v.sim) readerId[v.sim] = id;

const tools = [];
for (const [file, ids] of Object.entries(TRUTH.picks || {})) {
  const img = P.read(path.join(DIR, file));
  // At the cards' size the reader finds (smaller cards on some screens).
  const ui = S.scanPick(img, REF, null).ui;
  ids.forEach((sim, i) => {
    if (!T.TOOLS[sim]) throw new Error(`${file}: ${sim} isn't an instrument the simulator knows`);
    const box = S.pickArtBox(img, i - 1, ui);
    if (!box) {
      console.log(`${file}: card ${i + 1} (${sim}) wasn't found, left out`);
      return;
    }
    tools.push({ sim, feat: pack(S.artFeature(img, ...box)) });
  });
}

const icons = [];
for (const [file, ids] of Object.entries(TRUTH.panels || {})) {
  const img = P.read(path.join(DIR, file));
  const loc = S.locateBoard(img, S.grayOf(img), REF);
  const found = loc ? S.findToolIcons(img, loc).icons : [];
  if (found.length !== ids.length) {
    console.log(`${file}: ${found.length} icons found, ${ids.length} labeled, left out`);
    continue;
  }
  ids.forEach((sim, i) => {
    if (!readerId[sim]) throw new Error(`${file}: ${sim} has no reader id in js/scan-data.js`);
    // w: the icon's width in this picture; js/scan.js matches it only to icons
    // at least 60% that wide.
    icons.push({ id: readerId[sim], from: 'panel', w: Math.round(found[i].box[2] - found[i].box[0]), feat: pack(S.artFeature(img, ...found[i].box)) });
  });
}

// Start cards' badges, under the instrument panel: { "file.png": "opulence" }.
const badges = [];
for (const [file, id] of Object.entries(TRUTH.badges || {})) {
  const img = P.read(path.join(DIR, file));
  const loc = S.locateBoard(img, S.grayOf(img), REF);
  const label = loc ? S.findToolIcons(img, loc).label : null;
  if (!label) {
    console.log(`${file}: the instrument panel wasn't found, left out`);
    continue;
  }
  badges.push({ id, feat: pack(S.artFeature(img, ...S.badgeBox(label, true))) });
}

const date = new Date().toISOString().slice(0, 10);
const out = `/* Generated by tools/pick-build.js on ${date} from labeled screenshots of the live game. Do not edit by hand. */
(function (root) {
  root.TARTARUS_PICK = ${JSON.stringify({ generated: date, tools, icons, badges })};
  if (typeof module === 'object' && module.exports) module.exports = root.TARTARUS_PICK;
})(typeof window !== 'undefined' ? window : typeof self !== 'undefined' ? self : globalThis);
`;
fs.writeFileSync(path.join(ROOT, 'js', 'pick-data.js'), out);
console.log(`js/pick-data.js: ${tools.length} pick cards (${[...new Set(tools.map((t) => t.sim))].length} instruments), ${icons.length} panel icons (${icons.map((t) => t.id).join(', ')})`);

// Each screenshot read back with what was just built.
const PICK = { tools, icons, badges };
for (const [file, ids] of Object.entries(TRUTH.picks || {})) {
  const r = S.scanPick(P.read(path.join(DIR, file)), REF, PICK);
  const got = r.ok ? r.cards.map((c) => c.sim) : [];
  console.log(`${file}: ${r.ok ? got.map((g, i) => (g === ids[i] ? g : `${g} (want ${ids[i]})`)).join(', ') : r.reason}${r.ok ? `, re-roll ${r.reroll ? 'shown' : 'not shown'}` : ''}`);
}
const withIcons = S.withPanelIcons(REF, PICK);
for (const [file, ids] of Object.entries(TRUTH.panels || {})) {
  const r = S.scan(P.read(path.join(DIR, file)), withIcons);
  const got = r.ok && r.tools ? r.tools.tools.map((t) => (REF.toolNames[t.id] || {}).sim || t.id) : [];
  console.log(`${file}: ${got.map((g, i) => (g === ids[i] ? g : `${g} (want ${ids[i]})`)).join(', ')}`);
}
for (const [file, id] of Object.entries(TRUTH.badges || {})) {
  const r = S.scan(P.read(path.join(DIR, file)), withIcons);
  console.log(`${file}: badge ${r.ok && r.badge ? `${r.badge.id} (${r.badge.score})` : 'none'}${r.ok && r.badge && r.badge.id === id ? '' : ` (want ${id})`}`);
}
